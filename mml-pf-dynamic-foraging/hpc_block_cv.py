SBATCH_TEMPLATE = """#!/bin/bash
#SBATCH -p celltypes
#SBATCH --job-name blockcv
#SBATCH --time {time}
#SBATCH --nodes 1
#SBATCH --mem {mem}
#SBATCH -c {cores}
#SBATCH --array=0-{last}%50
#SBATCH -o {log_dir}/blockcv_%A_%a.out
#SBATCH -e {log_dir}/blockcv_%A_%a.err

# One array task per subject. The %50 throttle matches the documented cap of
# ~50 simultaneously scheduled jobs; the rest queue and start as slots free.

set -euo pipefail

# pip/joblib scratch must live somewhere writable on /allen, not the default
export TMPDIR="{tmp_dir}"
mkdir -p "$TMPDIR" "{log_dir}" "{out_dir}"

# the parallelism is across subjects and placements, so keep BLAS single-threaded
# inside each worker -- oversubscribing the cores runs SLOWER than serial
export OMP_NUM_THREADS=1
export OPENBLAS_NUM_THREADS=1
export MKL_NUM_THREADS=1
export NUMEXPR_NUM_THREADS=1
export VECLIB_MAXIMUM_THREADS=1

source activate {env}
cd {code_dir}

python hpc_block_cv.py run \\
    --cache-dir {cache_dir} \\
    --out-dir {out_dir} \\
    --task-id "$SLURM_ARRAY_TASK_ID" \\
    --cores {cores} \\
    --seeds {seeds} \\
    --block {block} \\
    --test-frac {test_frac}
"""


def write_sbatch(path, n_tasks, code_dir, cache_dir, out_dir, log_dir, tmp_dir,
                 env, cores, mem, time_limit, seeds, block, test_frac):
    # every path in the script must be ABSOLUTE: the task does `cd $code_dir`
    # first, so a relative cache/out path would resolve somewhere else.
    # os.path.abspath alone is not enough -- on some sandboxed filesystems it
    # returns the input unchanged -- so join against cwd explicitly.
    def _abs(p):
        p = os.path.expanduser(str(p))
        if not p.startswith("/"):
            p = os.path.normpath(os.path.join(os.getcwd(), p))
        return p

    paths = {k: _abs(v) for k, v in
             dict(log_dir=log_dir, tmp_dir=tmp_dir, code_dir=code_dir,
                  cache_dir=cache_dir, out_dir=out_dir).items()}
    rel = [f"{k}={v}" for k, v in paths.items() if not v.startswith("/")]
    if rel:
        raise ValueError(
            "could not resolve these to absolute paths, and the array task "
            f"cd's before using them: {rel}. Pass absolute /allen/... paths.")
    txt = SBATCH_TEMPLATE.format(
        last=max(n_tasks - 1, 0), env=env, cores=cores, mem=mem,
        time=time_limit, seeds=seeds, block=block, test_frac=test_frac,
        **paths)
    with open(path, "w") as f:
        f.write(txt)
    os.chmod(path, 0o755)
    print(f"wrote {path}  ({n_tasks} array tasks)")
    print(f"  submit with: sbatch {path}")
    return path


# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("stage", choices=["prepare", "run", "combine", "write-sbatch"])
    ap.add_argument("--cache-dir", default="./cache")
    ap.add_argument("--out-dir", default="./results")
    # --array_id is the name used in the lab's existing submit scripts; keep it
    # as an alias so a subjob.sh written for either convention works
    ap.add_argument("--task-id", "--array_id", type=int, default=None,
                    dest="task_id")
    ap.add_argument("--subjects", type=int, default=N_SUBJECTS)
    ap.add_argument("--sessions", type=int, default=N_SESSIONS)
    ap.add_argument("--seeds", type=int, default=SEEDS)
    ap.add_argument("--block", type=int, default=BLOCK)
    ap.add_argument("--test-frac", type=float, default=TEST_FRAC)
    ap.add_argument("--min-trials", type=int, default=MIN_TRIALS)
    ap.add_argument("--cores", type=int, default=1)
    # write-sbatch options
    ap.add_argument("--sbatch-path", default="hpc_block_cv_array.sh")
    ap.add_argument("--code-dir", default=None)
    ap.add_argument("--log-dir", default=None)
    ap.add_argument("--tmp-dir", default=None)
    ap.add_argument("--env", default="foraging")
    ap.add_argument("--mem", default="8G")
    ap.add_argument("--time-limit", default="08:00:00")
    args = ap.parse_args()

    if args.stage == "prepare":
        prepare(args.cache_dir, n_subjects=args.subjects,
                n_sessions=args.sessions, min_trials=args.min_trials)

    elif args.stage == "run":
        if args.task_id is None:
            ap.error("--task-id is required for stage 'run' "
                     "(SLURM provides $SLURM_ARRAY_TASK_ID)")
        run_task(args.cache_dir, args.out_dir, args.task_id, seeds=args.seeds,
                 block=args.block, test_frac=args.test_frac, cores=args.cores)

    elif args.stage == "combine":
        combine(args.out_dir)

    elif args.stage == "write-sbatch":
        mf_path = os.path.join(args.cache_dir, "manifest.csv")
        if not os.path.exists(mf_path):
            ap.error(f"{mf_path} not found -- run stage 'prepare' first, so the "
                     f"array width matches the actual number of subjects")
        n_tasks = len(pd.read_csv(mf_path))
        code_dir = args.code_dir or os.path.dirname(os.path.abspath(__file__))
        log_dir = args.log_dir or os.path.join(code_dir, "logs")
        tmp_dir = args.tmp_dir or os.path.join(code_dir, "tmp")
        # do NOT mkdir these -- the generator may run somewhere the target paths
        # do not exist (or are not writable). The array script creates TMPDIR
        # itself at runtime; SLURM needs the log dir to exist, so make it on the
        # cluster before submitting:
        #     mkdir -p <log_dir>
        write_sbatch(args.sbatch_path, n_tasks, code_dir,
                     os.path.abspath(args.cache_dir),
                     os.path.abspath(args.out_dir), log_dir, tmp_dir,
                     args.env, args.cores, args.mem, args.time_limit,
                     args.seeds, args.block, args.test_frac)


if __name__ == "__main__":
    main()
